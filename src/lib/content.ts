/** Flattens every translatable content string into a deduplicated array. */
export function collectContentStrings(): string[] {
  const out: string[] = [];
  for (const t of TUTORIALS) {
    out.push(t.title, t.tagline, t.outcome);
    for (const s of t.steps) {
      out.push(s.title, s.focus, s.dosage, s.anatomy, s.tool, s.formula, s.tip);
    }
  }
  for (const b of BRUSHES) {
    out.push(b.name, b.bristle, b.density, b.movement, b.bestFor, ...b.formulas);
  }
  return Array.from(new Set(out));
}
